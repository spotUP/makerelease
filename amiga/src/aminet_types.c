int rp_aminet_type_index(const char *type) {
    int i;
    for (i = 0; rp_aminet_types[i]; i++)
        if (!strcmp(rp_aminet_types[i], type)) return i;
    return -1;
}

static int ieq(const char *a, const char *b) {
    for (; *a && *b; a++, b++) {
        char x = *a, y = *b;
        if (x >= 'A' && x <= 'Z') x = (char)(x + 32);
        if (y >= 'A' && y <= 'Z') y = (char)(y + 32);
        if (x != y) return 0;
    }
    return *a == *b;
}

/* aminet-guess.ts: musicdisk -> mods/sets, video -> pix/anim (Aminet has no gfx/anim); every target is checked against the list. */
const char *rp_aminet_guess_type(const char *category, const char *platform_tag) {
    static const char *const by_cat[][2] = {
        { "intro", "demo/intro" }, { "musicdisk", "mods/sets" }, { "music", "mods/misc" }, { "graphics", "pix/art" },
        { "tool", "util/misc" }, { "door", "comm/bbs" }, { "video", "pix/anim" },
    };
    const char *guess = "";
    size_t i;
    if (!category) category = "";
    if (!platform_tag) platform_tag = "";
    for (i = 0; i < sizeof(by_cat) / sizeof(by_cat[0]); i++)
        if (ieq(category, by_cat[i][0])) guess = by_cat[i][1];
    if (ieq(category, "demo")) guess = ieq(platform_tag, "A1200") ? "demo/aga" : ieq(platform_tag, "A500") ? "demo/ecs" : "demo/misc";
    return rp_aminet_type_index(guess) >= 0 ? guess : "";
}
